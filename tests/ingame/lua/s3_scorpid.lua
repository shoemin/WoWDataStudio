-- s3_scorpid.lua: 9 yd south-west of Scorpid Worker spawn 8552 (-688, -4151, facing it), camera 7 yd behind. #2 Scorpion.m2 mesh
-- (stinger and pincers x2): the idle / wandering scorpid from behind the character and from the side, then Curse of Weakness (no damage)
-- makes it run to the character and attack: pictures of the run and attack animations, plus an external wowshot series of the attacks.
SC_Step(18, 'settle', function() VT_Facts(); VT_UI(false) end)
SC_Step(1.5, 'target', function() SC_Hw('TargetByName("Scorpid Worker")') end)
SC_Step(1.5, 'idle 1', function() VT_Target(); VT_UI(false); VT_Shot('s3_idle1') end)
SC_Step(1.3, 'side', function() FlipCameraYaw(60) end)
SC_Step(1.5, 'idle 2', function() VT_Shot('s3_idle2') end)
SC_Step(2.0, 'idle 3', function() VT_Shot('s3_idle3') end)
SC_Step(1.3, 'back', function() FlipCameraYaw(-60) end)
SC_Step(1.2, 'aggro', function() SC_Hw('CastSpellByName("Curse of Weakness")') end)
SC_Step(1.0, 'run', function() VT_Target(); VT_Shot('s3_move') end)
SC_Step(1.3, 'attack 1', function() VT_Shot('s3_attack1') end)
SC_Step(1.3, 'side 2', function() FlipCameraYaw(80); VT_Burst('scorpid', 4) end)
SC_Step(1.3, 'attack 2', function() VT_Shot('s3_attack2') end)
SC_Step(1.3, 'attack 3', function() VT_Shot('s3_attack3') end)
SC_Step(1.3, 'attack 4', function() VT_Target(); VT_Shot('s3_attack4') end)
SC_Step(1, 'end', function() VT_UI(true) end)
SC_Start()
